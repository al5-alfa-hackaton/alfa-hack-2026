export function delay(ms: number, signal: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal.aborted)
      return reject(new DOMException("Отменено", "AbortError"));
    const abort = () => {
      clearTimeout(timer);
      reject(new DOMException("Отменено", "AbortError"));
    };
    const timer = setTimeout(() => {
      signal.removeEventListener("abort", abort);
      resolve();
    }, ms);
    signal.addEventListener("abort", abort, { once: true });
  });
}
export async function runAnalysis(
  scenario: Scenario,
  signal: AbortSignal,
  progress: (step: number) => void,
  duration = 650,
) {
  for (let i = 0; i < steps.length; i++) {
    progress(i);
    await delay(duration, signal);
    if (i === 1 && ["error", "budget", "denied"].includes(scenario))
      throw new Error(scenario);
  }
  return scenario === "partial"
    ? "partial"
    : scenario === "empty"
      ? "empty"
      : "complete";
}
export function answerQuestion(
  question: string,
  item: News,
  company: CompanyId,
  role: Role,
) {
  const q = question.toLowerCase(),
    c = item.context[company];
  if (/риск|опас|угроз/.test(q))
    return `${c.risk} ${companies[company].missing}`;
  if (/действ|сделать|шаг|рекоменд/.test(q))
    return `${c.action} ${role === "cfo" ? "Для CFO приоритет — влияние на денежный поток." : "Для директора приоритет — влияние на стратегию и операционную устойчивость."}`;
  if (/источник|основан|откуда/.test(q))
    return `Основание: «${item.source}» и синтетический профиль «${companies[company].name}». ${c.reason} Все документы доступны во вкладке «Источники».`;
  if (/влия|важ|компан|почему/.test(q))
    return `${c.impact} Основание: ${c.reason}`;
  return "В демо нет языковой модели, поэтому я не могу достоверно ответить на произвольный вопрос. Выберите вопрос о влиянии, рисках, действиях или источниках. Для количественного прогноза нужны дополнительные данные.";
}
