export function rankedNews(company: CompanyId, role: Role) {
  return news
    .map((item) => ({
      ...item,
      score: Math.min(
        99,
        Math.max(1, item.weights[company] + (role === "ceo" ? item.ceo : 0)),
      ),
    }))
    .sort((a, b) => b.score - a.score);
}
